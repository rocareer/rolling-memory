package cli

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

// 接线生成物的固定形状（internal/plugins/register_gen.go）：
// 头部生成标记 + 固定说明 + package 子句；有注册行时再加一个只含空白导入的 import 块。
// 出厂登记态 = 无注册行（空骨架）——空骨架与生成器输出的空清单必须逐字节一致，
// 由 CheckSkeleton 与单测钉住（P5 的 check-plugin-registry.sh 走同一口径）。
const (
	// GeneratedMarker 生成物标记（Go 约定：须早于文件中第一处非注释文本）
	GeneratedMarker = "// Code generated by aigo plugin; DO NOT EDIT."
	// generatedNote 生成物说明（固定两行，重生成时不漂移）
	generatedNote = "// 本文件由安装器维护：每个已安装插件一行空白导入（插件包在 init() 里调 host.Register 登记）。\n" +
		"// 出厂登记态 = 空骨架（无注册行）；说明见同包 wiring.go 与 plugins/README.md。\n"
)

// registryImportPattern 解析空白导入行里的插件名（只认本模块 plugins/ 下的包）
var registryImportPattern = regexp.MustCompile(`_ "` + regexp.QuoteMeta(ModulePath) + `/plugins/([a-z0-9-]+)"`)

// BuildRegistryFile 生成 register_gen.go 内容（names 为插件名清单；空清单 ⇒ 空骨架）。
// 固定顺序：标记 + 说明 + package 子句（+ 排序去重后的空白导入块）。
func BuildRegistryFile(names []string) []byte {
	sorted := make([]string, 0, len(names))
	for _, name := range names {
		if name = strings.TrimSpace(name); name != "" && !slices.Contains(sorted, name) {
			sorted = append(sorted, name)
		}
	}
	slices.Sort(sorted)

	var b strings.Builder
	b.WriteString(GeneratedMarker + "\n")
	b.WriteString(generatedNote)
	b.WriteString("\npackage plugins\n")
	if len(sorted) > 0 {
		b.WriteString("\nimport (\n")
		for _, name := range sorted {
			fmt.Fprintf(&b, "\t_ %q\n", ImportPath(name))
		}
		b.WriteString(")\n")
	}
	return []byte(b.String())
}

// CheckSkeleton 校验 register_gen.go 是生成物且内容与生成器一致（P5 门禁同口径）：
// 生成标记存在、gofmt 干净（内容由本包生成即为规范形态）、无「注册行与源码不匹配」的漂移。
func CheckSkeleton(root string) error {
	content, err := os.ReadFile(registryPath(root))
	if err != nil {
		return fmt.Errorf("读取 %s 失败: %w", RegistryFile, err)
	}
	if !strings.HasPrefix(string(content), GeneratedMarker) {
		return fmt.Errorf("%s 缺少生成标记 %q（该文件是安装器生成物，勿手工改写）", RegistryFile, GeneratedMarker)
	}
	names, err := RegisteredPluginsFrom(content)
	if err != nil {
		return err
	}
	if want := string(BuildRegistryFile(names)); want != string(content) {
		return fmt.Errorf("%s 与生成器输出不一致（用 `aigo plugin install/uninstall` 重放，勿手工编辑）", RegistryFile)
	}
	return nil
}

// RegisteredPluginsFrom 从 register_gen.go 内容解析已注册的插件名（升序）
func RegisteredPluginsFrom(content []byte) ([]string, error) {
	names := []string{}
	for _, match := range registryImportPattern.FindAllStringSubmatch(string(content), -1) {
		names = append(names, match[1])
	}
	slices.Sort(names)
	return slices.Compact(names), nil
}

// RegisteredPlugins 读取仓库里的 register_gen.go，返回已注册插件名（文件不存在 ⇒ 空清单）
func RegisteredPlugins(root string) ([]string, error) {
	content, err := os.ReadFile(registryPath(root))
	if err != nil {
		if os.IsNotExist(err) {
			return []string{}, nil
		}
		return nil, fmt.Errorf("读取 %s 失败: %w", RegistryFile, err)
	}
	return RegisteredPluginsFrom(content)
}

// RegistryDiff 渲染 register_gen.go 的前后差异（公共前缀/后缀裁剪后的 -/+ 行；
// 该文件由生成器产出，改动形态就是「增删一行导入」，无需通用 diff 算法）
func RegistryDiff(current, next []byte) string {
	before := strings.Split(string(current), "\n")
	after := strings.Split(string(next), "\n")

	head := 0
	for head < len(before) && head < len(after) && before[head] == after[head] {
		head++
	}
	tail := 0
	for tail < len(before)-head && tail < len(after)-head &&
		before[len(before)-1-tail] == after[len(after)-1-tail] {
		tail++
	}

	var b strings.Builder
	for _, line := range before[head : len(before)-tail] {
		fmt.Fprintf(&b, "  - %s\n", line)
	}
	for _, line := range after[head : len(after)-tail] {
		fmt.Fprintf(&b, "  + %s\n", line)
	}
	if b.Len() == 0 {
		return "（无变化）\n"
	}
	return b.String()
}

// registryPath 生成物的绝对路径
func registryPath(root string) string {
	return filepath.Join(root, filepath.FromSlash(RegistryFile))
}
