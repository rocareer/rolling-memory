// sampleWirePacket is the shared fixture for transport-level tests (small, two sentences).
func sampleWirePacket() thinclient.BlindPulsePacket {
	return thinclient.BlindPulsePacket{
		UnitID: "bg:abc#0",
		Layer:  "background",
		Slots: []thinclient.BlindTokenAtom{
			{H: 0x0102030405060708, RawBitsX10: 120, ClassFlags: 1},
			{H: 0x1112131415161718, RawBitsX10: 200, ClassFlags: 2},
			{H: 0x2122232425262728, RawBitsX10: 330, ClassFlags: 4},
		},
		SentenceFrames: [][]thinclient.BlindTokenAtom{
			{{H: 0x0102030405060708, RawBitsX10: 120, ClassFlags: 1}, {H: 0x1112131415161718, RawBitsX10: 200, ClassFlags: 2}},
			{{H: 0x2122232425262728, RawBitsX10: 330, ClassFlags: 4}},
		},
	}
}

// TestPulsePayloadRoundTrip pins the single on-wire encoding: atoms plus sentence boundaries
// survive the payload losslessly (bit-for-bit), so the engine sees the exact same pulse.
func TestPulsePayloadRoundTrip(t *testing.T) {
	pkt := sampleWirePacket()
	payload, err := thinclient.EncodePulsePayload(pkt)
	if err != nil {
		t.Fatalf("EncodePulsePayload: %v", err)
	}
	atoms, offsets, err := thinclient.DecodePulsePayloadB64(payload)
	if err != nil {
		t.Fatalf("DecodePulsePayloadB64: %v", err)
	}
	if len(atoms) != len(pkt.Slots) {
		t.Fatalf("atom count %d != %d", len(atoms), len(pkt.Slots))
	}
	for i := range atoms {
		if atoms[i] != pkt.Slots[i] {
			t.Fatalf("atom %d mismatch: %+v != %+v", i, atoms[i], pkt.Slots[i])
		}
	}
	want := []int{2, 3}
	if len(offsets) != len(want) {
		t.Fatalf("offsets %v != %v", offsets, want)
	}
	for i := range want {
		if offsets[i] != want[i] {
			t.Fatalf("offsets %v != %v", offsets, want)
		}
	}
	// Cross-repo byte pin: the literal below is produced by the engine's authoritative
	// encoder (the service engine's blindwire/pulse.go) for these exact atoms and
	// offsets, and the live engine both decodes this payload and resolves the unit
	// (TestLiveUpstreamV1Integration_UserID10) — so the client and the service stay
	// byte-for-byte identical on the single payload format.
	const wantPayload = "Uk1CUAEBPwMAAwAAAAMAAnjIAcoCIQQBAgMEBQYHCBAQEBAQEBAQEBAQEBAQEBAYAQA="
	if payload != wantPayload {
		t.Fatalf("payload drifted from the pinned bytes:\n got %s\nwant %s", payload, wantPayload)
	}
	t.Logf("payload (%d B base64) pinned as %s", len(payload), wantPayload)
}

// TestPulsePayloadMatchesEngineVectors pins the ported codec against engine-authoritative
// payloads: every literal below was generated by the engine's encoder
// (the service engine's blindwire/pulse.go) for the same atoms and sentence offsets,
// covering the empty payload, the single-atom and identity fast paths, dictionary
// repeats with a first-appearance escape, and wide unsorted H values.
func TestPulsePayloadMatchesEngineVectors(t *testing.T) {
	atom := func(h uint64, b uint16, f uint8) thinclient.BlindTokenAtom {
		return thinclient.BlindTokenAtom{H: h, RawBitsX10: b, ClassFlags: f}
	}
	cases := []struct {
		name    string
		slots   []thinclient.BlindTokenAtom
		offsets []int
		want    string
	}{
		{"empty", nil, nil, "Uk1CUAEBAAAAAAAAAAAAAA=="},
		{"single", []thinclient.BlindTokenAtom{atom(0x0102030405060708, 120, 1)}, []int{1},
			"Uk1CUAEBQAEAAQAAAAEAAXgBAQIDBAUGBwgA"},
		{"identity-3", []thinclient.BlindTokenAtom{
			atom(0x0102030405060708, 120, 1),
			atom(0x1112131415161718, 200, 2),
			atom(0x2122232425262728, 330, 4),
		}, []int{2, 3}, "Uk1CUAEBPwMAAwAAAAMAAnjIAcoCIQQBAgMEBQYHCBAQEBAQEBAQEBAQEBAQEBAYAQA="},
		{"dupes-and-repeat", []thinclient.BlindTokenAtom{
			atom(0xAA, 120, 1), atom(0xBB, 200, 2), atom(0xAA, 120, 1),
			atom(0xCC, 330, 4), atom(0xBB, 200, 2), atom(0xAA, 120, 1),
		}, []int{3, 6}, "Uk1CUAEAPwMAAwAAAAYAAnjIAcoCIQQAAAAAAAAAqgAAAAAAAAARAAAAAAAAABEYIgACAg=="},
		{"wide-h-unsorted", []thinclient.BlindTokenAtom{
			atom(0xFFFFFFFFFFFFFFF0, 700, 8), atom(0x10, 12, 1),
			atom(0x8000000000000000, 9, 15), atom(0x10, 12, 1),
		}, []int{2, 4}, "Uk1CUAEAPwMAAwAAAAQAAgkMvAUfCAAAAAAAAAAQf/////////B/////////8EoIAQE="},
	}
	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			frames := make([][]thinclient.BlindTokenAtom, 0, len(testCase.offsets))
			prev := 0
			for _, off := range testCase.offsets {
				frames = append(frames, testCase.slots[prev:off])
				prev = off
			}
			pkt := thinclient.BlindPulsePacket{UnitID: "u", Slots: testCase.slots, SentenceFrames: frames}
			payload, err := thinclient.EncodePulsePayload(pkt)
			if err != nil {
				t.Fatalf("EncodePulsePayload: %v", err)
			}
			if payload != testCase.want {
				t.Fatalf("payload != engine vector:\n got %s\nwant %s", payload, testCase.want)
			}
			atoms, offsets, err := thinclient.DecodePulsePayloadB64(payload)
			if err != nil {
				t.Fatalf("DecodePulsePayloadB64: %v", err)
			}
			if len(atoms) != len(testCase.slots) || len(offsets) != len(testCase.offsets) {
				t.Fatalf("round trip sizes = %d/%d, want %d/%d", len(atoms), len(offsets), len(testCase.slots), len(testCase.offsets))
			}
			for i := range atoms {
				if atoms[i] != testCase.slots[i] {
					t.Fatalf("atom %d = %+v, want %+v", i, atoms[i], testCase.slots[i])
				}
			}
			for i := range offsets {
				if offsets[i] != testCase.offsets[i] {
					t.Fatalf("offset %d = %d, want %d", i, offsets[i], testCase.offsets[i])
				}
			}
		})
	}
}

// TestPulsePayloadSentenceFramesOnly verifies callers that only set sentence frames still encode.
func TestPulsePayloadSentenceFramesOnly(t *testing.T) {
	pkt := sampleWirePacket()
	pkt.Slots = nil
	payload, err := thinclient.EncodePulsePayload(pkt)
	if err != nil {
		t.Fatalf("EncodePulsePayload: %v", err)
	}
	atoms, offsets, err := thinclient.DecodePulsePayloadB64(payload)
	if err != nil {
		t.Fatalf("DecodePulsePayloadB64: %v", err)
	}
	if len(atoms) != 3 || len(offsets) != 2 || offsets[1] != 3 {
		t.Fatalf("frames-only payload wrong: atoms=%d offsets=%v", len(atoms), offsets)
	}
}

// TestPulsePayloadFullFlagDomain guards the 8-bit flag domain at the encoder/decoder boundary:
// low 4 bits are character class, high 4 bits are declared form flags (bit5 focal header /
// bit6 boundary quote / bit7 quantity dyad side) — see the canonical SDK. The former 4-bit-domain
// rejection of 0x10 is superseded and the uint8 field bounds the value at compile time, so the
// reachable out-of-domain surface is the wire header flag byte.
func TestPulsePayloadFullFlagDomain(t *testing.T) {
	pkt := sampleWirePacket()
	pkt.SentenceFrames = nil
	pkt.Slots = []thinclient.BlindTokenAtom{{H: 1, RawBitsX10: 10, ClassFlags: 0xFF}}
	b64, err := thinclient.EncodePulsePayload(pkt)
	if err != nil {
		t.Fatalf("declared high-nibble flag rejected: %v", err)
	}
	atoms, _, err := thinclient.DecodePulsePayloadB64(b64)
	if err != nil || len(atoms) != 1 || atoms[0].ClassFlags != 0xFF {
		t.Fatalf("high-nibble flag round-trip failed: atoms=%+v err=%v", atoms, err)
	}

	raw, err := base64.StdEncoding.DecodeString(b64)
	if err != nil || len(raw) < 6 {
		t.Fatalf("decode payload bytes: %v", err)
	}
	raw[5] |= 0x80 // unknown header flag bit
	if _, _, err := thinclient.DecodePulsePayloadB64(base64.StdEncoding.EncodeToString(raw)); err == nil {
		t.Fatalf("unknown wire header flag must be rejected")
	}
}

// TestPulsePayloadFrameMismatchRejected guards against shipping inconsistent sentence boundaries.
func TestPulsePayloadFrameMismatchRejected(t *testing.T) {
	pkt := sampleWirePacket()
	pkt.SentenceFrames = pkt.SentenceFrames[:1] // covers 2 of 3 slots
	if _, err := thinclient.EncodePulsePayload(pkt); err == nil {
		t.Fatalf("frames covering fewer atoms than slots must be rejected")
	}
}

// TestDecodePulsePayloadRejectsGarbage keeps the decoder strict: non-conforming payloads fail
// loudly instead of producing a silently wrong pulse.
func TestDecodePulsePayloadRejectsGarbage(t *testing.T) {
	cases := []string{"", "AAAA", "Uk1CUQ==", strings.Repeat("A", 8)}
	for _, c := range cases {
		if _, _, err := thinclient.DecodePulsePayloadB64(c); err == nil {
			t.Fatalf("payload %q must be rejected", c)
		}
	}
}

// TestPulsePayloadSingleRootRepeatedAbove224Slots guards against the dictN==1 zero-bit-stream
// false-positive where slotN >= 225 previously tripped `slotN > len(raw)*8` on Decode.
func TestPulsePayloadSingleRootRepeatedAbove224Slots(t *testing.T) {
	slots := make([]thinclient.BlindTokenAtom, 300)
	for i := range slots {
		slots[i] = thinclient.BlindTokenAtom{H: 0x0102030405060708, RawBitsX10: 33, ClassFlags: 4}
	}
	pkt := thinclient.BlindPulsePacket{
		UnitID:         "u-300",
		Slots:          slots,
		SentenceFrames: [][]thinclient.BlindTokenAtom{slots[:150], slots[150:]},
	}
	b64, err := thinclient.EncodePulsePayload(pkt)
	if err != nil {
		t.Fatalf("EncodePulsePayload(300 repeated slots): %v", err)
	}
	gotAtoms, gotOffsets, err := thinclient.DecodePulsePayloadB64(b64)
	if err != nil {
		t.Fatalf("DecodePulsePayloadB64(300 repeated slots): %v", err)
	}
	if len(gotAtoms) != 300 || len(gotOffsets) != 2 || gotOffsets[0] != 150 || gotOffsets[1] != 300 {
		t.Fatalf("unexpected decoded 300-slot single-root payload: atoms=%d offsets=%v", len(gotAtoms), gotOffsets)
	}
}

